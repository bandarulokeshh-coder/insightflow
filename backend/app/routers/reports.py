"""Insight reports — business-friendly export (Markdown / HTML) + share JSON."""
from __future__ import annotations

from datetime import datetime, timezone

from fastapi import APIRouter, Depends
from fastapi.responses import PlainTextResponse
from sqlmodel import Session, select

from .. import analysis, models
from ..database import get_session

router = APIRouter(prefix="/api/reports", tags=["reports"])


def _build(session: Session) -> dict:
    rows = list(session.exec(
        select(models.Feedback).where(models.Feedback.is_duplicate == False)  # noqa: E712
    ).all())
    items = [{
        "text": r.adapted_text or r.text,
        "sentiment": r.sentiment or "neutral",
        "topic": r.topic or "General",
        "urgency": r.urgency or 0,
        "created_at": (r.source_date or r.created_at).isoformat() if (r.source_date or r.created_at) else "",
    } for r in rows]

    recs = analysis.compute_recommendations(items)
    run = session.exec(
        select(models.AdaptionRun).where(models.AdaptionRun.status == "succeeded")  # type: ignore[attr-defined]
    ).all()
    run = run[-1] if run else None
    issues = session.exec(select(models.Issue).order_by(models.Issue.priority.desc())).all()  # type: ignore[attr-defined]

    total = len(items)
    neg = sum(1 for i in items if i["sentiment"] == "negative")
    return {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "headline": {
            "total_feedback": total,
            "negative_share": round(neg / total, 3) if total else 0,
            "top_priority": recs[0]["title"] if recs else None,
            "data_quality": {
                "grade_before": run.grade_before if run else None,
                "grade_after": run.grade_after if run else None,
                "improvement_percent": run.improvement_percent if run else None,
                "mode": run.mode if run else None,
            },
        },
        "recommendations": recs[:6],
        "tracked_issues": [i.model_dump() for i in issues],
        "topic_distribution": [
            {"topic": t, "total": c, "negative": n}
            for t, c, n in sorted(_topic_counts(items), key=lambda x: -x[1])
        ],
    }


