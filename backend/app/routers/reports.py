def _to_markdown(rep: dict) -> str:
    h = rep["headline"]
    dq = h["data_quality"]
    lines = [
        "# InsightFlow — Customer Insight Report",
        f"_Generated {rep['generated_at'][:19]} UTC_",
        "",
        "## Executive summary",
        "",
        f"- **{h['total_feedback']}** feedback items analyzed",
        f"- **{round(h['negative_share'] * 100)}%** of feedback is negative",
        f"- Top priority: **{h['top_priority'] or 'n/a'}**",
    ]
    if dq.get("grade_after") is not None:
        lines.append(
            f"- Data quality improved **{dq['grade_before']} → {dq['grade_after']}** "
            f"(+{dq['improvement_percent']}%) via Adaptive Data ({dq['mode']} mode)"
        )
    lines += ["", "## Priority recommendations", ""]
    for i, r in enumerate(rep["recommendations"], 1):
        lines += [
            f"### {i}. {r['title']}  —  priority {r['priority']} ({r['priority_label']})",
            "",
            f"**Why:** {r['why']}",
            "",
            f"**Recommended action:** {r['action']}",
            "",
        ]
        for ex in r["examples"][:2]:
            lines.append(f"> {ex}")
        lines.append("")
    if rep["tracked_issues"]:
        lines += ["## Tracked issues", ""]
        lines += ["| Priority | Issue | Status |", "|---|---|---|"]
        for i in rep["tracked_issues"]:
            lines.append(f"| {i['priority']} | {i['title']} | {i['status']} |")
        lines.append("")
    lines += ["## Topic distribution", "", "| Topic | Items | Negative |", "|---|---|---|"]
    for t in rep["topic_distribution"]:
        lines.append(f"| {t['topic']} | {t['total']} | {t['negative']} |")
    lines += ["", "---", "_Generated by InsightFlow — AI × Web · Build Battle 2026_"]
    return "\n".join(lines)


@router.get("/insight")
def insight(session: Session = Depends(get_session)):
    return _build(session)


@router.get("/export", response_class=PlainTextResponse)
def export_report(format: str = "md", session: Session = Depends(get_session)):
    rep = _build(session)
    if format == "json":
        return PlainTextResponse(
            __import__("json").dumps(rep, indent=2),
            media_type="application/json",
            headers={"Content-Disposition": "attachment; filename=insightflow-report.json"},
        )
    return PlainTextResponse(
        _to_markdown(rep),
        media_type="text/markdown; charset=utf-8",
        headers={"Content-Disposition": "attachment; filename=insightflow-report.md"},
    )
